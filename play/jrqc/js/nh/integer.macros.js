export function AppendLongDigit(L, D) {
    return L < 922337203685477580n || L === 922337203685477580n && D <= 7 ? $c.add64($c.mul64(L, 10), D) : -1;
}
export function nowrap_add(a, b) {
    return a <= $c.sub64(9223372036854775807n, b) ? $c.add64(a, b) : 9223372036854775807n;
}
