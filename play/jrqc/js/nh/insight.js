/* return a count of the number of extinct species */
/**
 * @returns {number} int
 */
function num_extinct() {   // insight.c:2970
    let i = 0, n = 0;
    n = 0;
    for (i = LOW_PM; i < NUMMONS; i = i + 1 | 0) {
        if (UniqCritterIndx(i)) {
            continue;
        }
        if ((svm.mvitals[i].mvflags & G_GONE) === G_EXTINCT) {
            n = n + 1 | 0;
        }
    }
    return n;
}
/* collect both genocides and extinctions, skipping uniques */
/**
 * @param {number} mvflags int
 * @param {*} mindx int *
 * @returns {number} int
 */
function num_gone(mvflags, mindx) {   // insight.c:2985
    let mflg = 0, i = 0, n = 0, $t1;
    mflg = $c.u8(mvflags);
    n = 0;
    $c.memset(mindx, 0, 1532);
    for (i = LOW_PM; i < NUMMONS; i = i + 1 | 0) {
        /* uniques can't be genocided but can become extinct;
           however, they're never reported as extinct, so skip them */
        if (UniqCritterIndx(i)) {
            continue;
        }
        if ((svm.mvitals[i].mvflags & mflg) !== 0) {
            mindx.set(($t1 = n, n = $t1 + 1 | 0, $t1), i);
        }
    }
    return n;
}
