/**
 * @param {*} vptr1 const void *
 * @param {*} vptr2 const void *
 * @returns {number} int
 */
function vanqsort_cmp(vptr1, vptr2) {   // insight.c:2621
    let indx1 = 0, indx2 = 0, mlev1 = 0, mlev2 = 0, mstr1 = 0, mstr2 = 0, uniq1 = 0, uniq2 = 0, died1 = 0, died2 = 0, res = 0, name1 = null, name2 = null, punct = null, mcls1 = 0, mcls2 = 0;
    indx1 = $c.asArr(vptr1, Int16Array).get(0);
    indx2 = $c.asArr(vptr2, Int16Array).get(0);
    switch (flags.vanq_sortmode) {
        default:
        case VANQ.MLVL_MNDX:
            /* sort by monster level */
            mlev1 = mons[indx1].mlevel;
            mlev2 = mons[indx2].mlevel;
            res = mlev2 - mlev1 | 0;   /* mlevel high to low */
            break;
        case VANQ.MSTR_MNDX:
            /* sort by monster toughness */
            mstr1 = mons[indx1].difficulty;
            mstr2 = mons[indx2].difficulty;
            res = mstr2 - mstr1 | 0;   /* monstr high to low */
            break;
        case VANQ.ALPHA_SEP:
            uniq1 = mons[indx1].geno & G_UNIQ && indx1 !== PM.HIGH_CLERIC ? 1 : 0;
            uniq2 = mons[indx2].geno & G_UNIQ && indx2 !== PM.HIGH_CLERIC ? 1 : 0;
            if (uniq1 ^ uniq2) {
                /* one or other uniq, but not both */
                res = uniq2 - uniq1 | 0;
                break;
            }   /* else both unique or neither unique */
        case VANQ.ALPHA_MIX:
            /*FALLTHRU*/
            name1 = mons[indx1].pmnames[NEUTRAL];
            name2 = mons[indx2].pmnames[NEUTRAL];
            res = strcmpi(name1, name2);   /* caseblind alpha, low to high */
            break;
        case VANQ.MCLS_HTOL:
        case VANQ.MCLS_LTOH:
            /* mons[].mlet is a small integer, 1..N, of type plain char;
               if 'char' happens to be unsigned, (mlet1 - mlet2) would yield
               an inappropriate result when mlet2 is greater than mlet1,
               so force our copies (mcls1, mcls2) to be signed */
            mcls1 = mons[indx1].mlet;
            mcls2 = mons[indx2].mlet;
            /* S_ANT through S_ZRUTY correspond to lowercase monster classes,
               S_ANGEL through S_ZOMBIE correspond to uppercase, and various
               punctuation characters are used for classes beyond those */
            if (mcls1 > S.ZOMBIE && mcls2 > S.ZOMBIE) {
                /* force a specific order to the punctuation classes that's
                   different from the internal order;
                   internal order is ok if neither or just one is punctuation
                   since letters have lower values so come out before punct */
                if ((punct = $c.strchr(new $c.Ptr(vanqsort_cmp$punctclasses, 0), mcls1)) !== null) {
                    mcls1 = $c.i8(S.ZOMBIE + 1 + $c.i32($c.pdiff(punct, new $c.Ptr(vanqsort_cmp$punctclasses, 0))) | 0);
                }
                if ((punct = $c.strchr(new $c.Ptr(vanqsort_cmp$punctclasses, 0), mcls2)) !== null) {
                    mcls2 = $c.i8(S.ZOMBIE + 1 + $c.i32($c.pdiff(punct, new $c.Ptr(vanqsort_cmp$punctclasses, 0))) | 0);
                }
            }
            res = mcls1 - mcls2 | 0;   /* class */
            if (res === 0) {
                /* Riders are in the same class as major demons, yielding res==0
                   above when both mcls1 and mcls2 are either Riders or demons or
                   one of each; force Riders to be sorted before demons */
                res = is_rider($c.relem(mons, indx2)) - is_rider($c.relem(mons, indx1)) | 0;
                /* res -1 => #1 is a Rider, #2 isn't;
                        0 => both Riders or neither;
                       +1 => #2 is a Rider, #1 isn't */
                if (res) {
                    break;
                }
                mlev1 = mons[indx1].mlevel;
                mlev2 = mons[indx2].mlevel;
                res = mlev1 - mlev2 | 0;   /* mlevel low to high */
                if (flags.vanq_sortmode === VANQ.MCLS_HTOL) {
                    res = -res | 0;   /* mlevel high to low */
                }
            }
            break;
        case VANQ.COUNT_H_L:
        case VANQ.COUNT_L_H:
            died1 = svm.mvitals[indx1].died;
            died2 = svm.mvitals[indx2].died;
            res = died2 - died1 | 0;   /* dead count high to low */
            if (flags.vanq_sortmode === VANQ.COUNT_L_H) {
                res = -res | 0;   /* dead count low to high */
            }
            break;
    }
    /* tiebreaker: internal mons[] index */
    if (res === 0) {
        res = indx1 - indx2 | 0;   /* mndx low to high */
    }
    return res;
}
