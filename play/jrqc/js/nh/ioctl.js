export async function dosuspend() {   // ioctl.c:161
    /* NB: check_user_string() is port-specific. */
    if (!sysopt.shellers || !sysopt.shellers.get(0) || !check_user_string(sysopt.shellers)) {
        await Norep($c.lit("Suspend command not available."));
        return 0;
    }
    if ($c.signal(18, $c.ptrConst(1)) === null) {
        await suspend_nhwindows()(null);
        $c.signal(18, null);
        $c.kill(0, 18);
        await resume_nhwindows()();
    } else {
        await pline($c.lit("I don't think your shell has job control."));
    }
    return 0;
}

