function changedline(p, oldpc, newpc) {   // ldebug.c:873
    let delta = 0, pc = 0, lineinfo = 0;
    if ($h.u32[(p + 88) >>> 2] === 0) {   /* no debug information? */
        return 0;
    }
    if ((newpc - oldpc | 0) < 64) {
        /* not too far apart? */
        delta = 0;   /* line difference */
        pc = oldpc;
        for (; ; ) {
            lineinfo = $h.i8[$h.u32[(p + 88) >>> 2] + (pc = pc + 1 | 0)];
            if (lineinfo === -128) {
                break;   /* cannot compute delta; fall through */
            }
            delta = delta + lineinfo | 0;
            if (pc === newpc) {
                return delta !== 0 ? 1 : 0;   /* delta computed successfully */
            }
        }
    }
    /* either instructions are too far apart or there is an absolute line
       info in the way; compute line difference explicitly */
    return luaG_getfuncline(p, oldpc) !== luaG_getfuncline(p, newpc) ? 1 : 0;
}
/*
** Traces Lua calls. If code is running the first instruction of a function,
** and function is not vararg, and it is not coming from an yield,
** calls 'luaD_hookcall'. (Vararg functions will call 'luaD_hookcall'
** after adjusting its variable arguments; otherwise, they could call
** a line/count hook before the call hook. Functions coming from
** an yield already called 'luaD_hookcall' before yielding.)
*/
/**
 * @param {number} L lua_State *
 * @returns {Promise<number>} int
 */
export async function luaG_tracecall(L) {   // ldebug.c:902
    let ci = 0, p = 0;
    ci = $h.u32[(L + 32) >>> 2];
    p = $h.u32[($h.u32[($h.u32[ci >>> 2]) >>> 2] + 24) >>> 2];
    $h.i32[(ci + 32 + 8) >>> 2] = 1;   /* ensure hooks will be checked */
    if ($h.u32[(ci + 32) >>> 2] === $h.u32[(p + 64) >>> 2]) {
        /* first instruction (not resuming)? */
        if ($h.u8[p + 11]) {
            return 0;   /* hooks will start at VARARGPREP instruction */
        } else if (!($h.u16[(ci + 62) >>> 1] & 64)) {   /* not yieded? */
            await luaD_hookcall(L, ci);   /* check 'call' hook */
        }
    }
    return 1;   /* keep 'trap' on */
}
/*
** Traces the execution of a Lua function. Called before the execution
** of each opcode, when debug is on. 'L->oldpc' stores the last
** instruction traced, to detect line changes. When entering a new
** function, 'npci' will be zero and will test as a new line whatever
** the value of 'oldpc'.  Some exceptional conditions may return to
** a function without setting 'oldpc'. In that case, 'oldpc' may be
** invalid; if so, use zero as a valid value. (A wrong but valid 'oldpc'
** at most causes an extra call to a line hook.)
** This function is not "Protected" when called, so it should correct
** 'L->top.p' before calling anything that can run the GC.
*/
/**
 * @param {number} L lua_State *
 * @param {number} pc const Instruction *
 * @returns {Promise<number>} int
 */
export async function luaG_traceexec(L, pc) {   // ldebug.c:928
    let ci = 0, mask = 0, p = 0, counthook = 0, oldpc = 0, npci = 0, newline = 0;
    ci = $h.u32[(L + 32) >>> 2];
    mask = $c.u8($h.i32[(L + 192) >>> 2]);
    p = $h.u32[($h.u32[($h.u32[ci >>> 2]) >>> 2] + 24) >>> 2];
    if (!(mask & 12)) {
        /* no hooks? */
        $h.i32[(ci + 32 + 8) >>> 2] = 0;   /* don't need to stop again */
        return 0;   /* turn off 'trap' */
    }
    pc = pc + 4;   /* reference is always next instruction */
    $h.stp(ci + 32, pc);   /* save 'pc' */
    counthook = mask & 8 && ($h.i32[(L + 188) >>> 2] = $h.i32[(L + 188) >>> 2] - 1 | 0) === 0 ? 1 : 0;
    if (counthook) {
        $h.i32[(L + 188) >>> 2] = $h.i32[(L + 184) >>> 2];   /* reset count */
    } else if (!(mask & 4)) {
        return 1;   /* no line hook and count != 0; nothing to be done now */
    }
    if ($h.u16[(ci + 62) >>> 1] & 64) {
        /* hook yielded last time? */
        $h.u16[(ci + 62) >>> 1] = $c.u16($h.u16[(ci + 62) >>> 1] & -65);   /* erase mark */
        return 1;   /* do not call hook again (VM yielded, so it did not move) */
    }
    if (!($h.u8[luaP_opmodes + (($h.u32[($h.u32[(ci + 32) >>> 2] - 4) >>> 2] >>> 0 & 127) >>> 0)] & 32 && (($h.u32[($h.u32[(ci + 32) >>> 2] - 4) >>> 2] >>> 16 & 255) >>> 0 | 0) === 0)) {   /* top not being used? */
        $h.stp(L + 16, $h.u32[(ci + 8) >>> 2]);   /* correct top */
    }
    if (counthook) {
        await luaD_hook(L, 3, -1, 0, 0);   /* call count hook */
    }
    if (mask & 4) {
        /* 'L->oldpc' may be invalid; use zero in this case */
        oldpc = $h.i32[(L + 180) >>> 2] < $h.i32[(p + 24) >>> 2] ? $h.i32[(L + 180) >>> 2] : 0;
        npci = $c.i32((pc - $h.u32[(p + 64) >>> 2]) / 4) - 1 | 0;
        /* call hook when jump back (loop), */
        if (npci <= oldpc || changedline(p, oldpc, npci)) {
            /* or when enter new line */
            newline = luaG_getfuncline(p, npci);
            await luaD_hook(L, 2, newline, 0, 0);   /* call line hook */
        }
        $h.i32[(L + 180) >>> 2] = npci;   /* 'pc' of last call to line hook */
    }
    if ($h.u8[L + 10] === 1) {
        /* did hook yield? */
        if (counthook) {
            $h.i32[(L + 188) >>> 2] = 1;   /* undo decrement to zero */
        }
        $h.u16[(ci + 62) >>> 1] = $c.u16($h.u16[(ci + 62) >>> 1] | 64);   /* mark that it yielded */
        await luaD_throw(L, 1);
    }
    return 1;   /* keep 'trap' on */
}

