/*
 * Creation of a drawbridge at pos x,y.
 *     dir is the direction.
 *     flag must be put to TRUE if we want the drawbridge to be opened.
 */
/**
 * @param {number} x coordxy
 * @param {number} y coordxy
 * @param {number} dir int
 * @param {number} flag boolean
 * @returns {Promise<number>} boolean
 */
export async function create_drawbridge(x, y, dir, flag) {   // dbridge.c:235
    let horiz = 0;
    const lava = svl.level.locations[x][y].typ === LAVAPOOL ? 1 : 0;   /* assume initialized map */
    let x2 = x;
    let y2 = y;
    switch (dir) {
        case DB.NORTH:
            horiz = TRUE;
            y2 = $c.i16(y2 - 1);
            break;
        case DB.SOUTH:
            horiz = TRUE;
            y2 = $c.i16(y2 + 1);
            break;
        case DB.EAST:
            horiz = FALSE;
            x2 = $c.i16(x2 + 1);
            break;
        default:
            await impossible($c.lit("bad direction in create_drawbridge"));
        case DB.WEST:
            /*FALLTHRU*/
            horiz = FALSE;
            x2 = $c.i16(x2 - 1);
            break;
    }
    if (!(svl.level.locations[x2][y2].typ && svl.level.locations[x2][y2].typ <= DBWALL)) {
        return FALSE;
    }
    if (flag) {
        /* We want the bridge open */
        svl.level.locations[x][y].typ = DRAWBRIDGE_DOWN;
        svl.level.locations[x2][y2].typ = DOOR;
        svl.level.locations[x2][y2].flags = (D.NODOOR) & 31;
    } else {
        svl.level.locations[x][y].typ = DRAWBRIDGE_UP;
        svl.level.locations[x2][y2].typ = DBWALL;
        /* Drawbridges are non-diggable. */
        svl.level.locations[x2][y2].flags = (W.NONDIGGABLE) & 31;
    }
    svl.level.locations[x][y].horizontal = (!horiz ? 1 : 0) & 1;
    svl.level.locations[x2][y2].horizontal = (horiz >>> 0) & 1;
    svl.level.locations[x][y].flags = (dir >>> 0) & 31;
    if (lava) {
        svl.level.locations[x][y].flags = ((svl.level.locations[x][y].flags | 0 | DB.LAVA) >>> 0) & 31;
    }
    return TRUE;
}
