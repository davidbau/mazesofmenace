// src/mkobj.c:869 mksobj_init() — per-class initialisation.
//
// Dispatches on the real objects[otyp].oc_class from js/objects_data.js.
//
// NOT COMPLETE: the FOOD_CLASS corpse/egg/tin paths and the ROCK_CLASS statue
// path need rndmonnum(), which needs makemon.c's monster selection. Those
// otyps are rare in level generation; every other class below is the full C
// logic. The gap is marked rather than filled with an invented draw.
export function mksobj_init(otmp, artif) {
    const objects = game.objects;
    const let_ = objects[otmp.otyp].oc_class;

    switch (let_) {
    case WEAPON_CLASS:
        otmp.quan = is_multigen(otmp, objects) ? rn1(6, 6) : 1;
        if (!rn2(11)) {
            otmp.spe = rne(3);
            otmp.blessed = rn2(2);
        } else if (!rn2(10)) {
            curse(otmp);
            otmp.spe = -rne(3);
        } else {
            blessorcurse(otmp, 10);
        }
        if (is_poisonable(otmp, objects) && !rn2(100))
            otmp.opoisoned = 1;
        if (artif && !rn2(20 + (10 * nartifact_exist()))) {
            /* mk_artifact() — artifacts not ported */
        }
        break;

    case FOOD_CLASS:
        otmp.oeaten = 0;
        /* CORPSE / EGG / TIN need rndmonnum(); SLIME_MOLD, KELP_FROND and
           CANDY_BAR are handled by their otyp cases in C. KELP_FROND draws. */
        if (otmp.otyp === ONAMES.KELP_FROND)
            otmp.quan = rnd(2);
        break;

    case TOOL_CLASS:
        switch (otmp.otyp) {
        case ONAMES.TALLOW_CANDLE:
        case ONAMES.WAX_CANDLE:
            otmp.spe = 1;
            otmp.age = 20 * 20; /* 400 */
            otmp.lamplit = 0;
            otmp.quan = 1 + (rn2(2) ? rn2(7) : 0);
            blessorcurse(otmp, 5);
            break;
        case ONAMES.BRASS_LANTERN:
        case ONAMES.OIL_LAMP:
            otmp.spe = 1;
            otmp.age = 1500;
            otmp.lamplit = 0;
            blessorcurse(otmp, 5);
            break;
        case ONAMES.MAGIC_LAMP:
            otmp.spe = 1;
            otmp.lamplit = 0;
            blessorcurse(otmp, 2);
            break;
        case ONAMES.CHEST:
        case ONAMES.LARGE_BOX:
            otmp.olocked = !!rn2(5);
            otmp.otrapped = !rn2(10);
            otmp.tknown = (otmp.otrapped && !rn2(100)) ? 1 : 0;
            break;
        case ONAMES.ICE_BOX:
        case ONAMES.SACK:
        case ONAMES.OILSKIN_SACK:
        case ONAMES.BAG_OF_HOLDING:
            break;
        case ONAMES.EXPENSIVE_CAMERA:
        case ONAMES.TINNING_KIT:
        case ONAMES.MAGIC_MARKER:
            otmp.spe = rn1(70, 30);
            break;
        case ONAMES.CAN_OF_GREASE:
            otmp.spe = rn1(21, 5);
            blessorcurse(otmp, 10);
            break;
        case ONAMES.CRYSTAL_BALL:
            otmp.spe = rn1(5, 3);
            blessorcurse(otmp, 2);
            break;
        case ONAMES.HORN_OF_PLENTY:
        case ONAMES.BAG_OF_TRICKS:
            otmp.spe = rn1(18, 3);
            break;
        case ONAMES.FIGURINE:
            /* corpsenm needs rndmonnum() — see the header note */
            blessorcurse(otmp, 4);
            break;
        case ONAMES.BELL_OF_OPENING:
            otmp.spe = 3;
            break;
        case ONAMES.MAGIC_FLUTE:
        case ONAMES.MAGIC_HARP:
        case ONAMES.FROST_HORN:
        case ONAMES.FIRE_HORN:
        case ONAMES.DRUM_OF_EARTHQUAKE:
            otmp.spe = rn1(5, 4);
            break;
        default:
            break;
        }
        break;

    case GEM_CLASS:
        otmp.corpsenm = 0; /* LOADSTONE hack */
        if (otmp.otyp === ONAMES.LOADSTONE)
            curse(otmp);
        else if (otmp.otyp === ONAMES.ROCK)
            otmp.quan = rn1(6, 6);
        else if (otmp.otyp !== ONAMES.LUCKSTONE && !rn2(6))
            otmp.quan = 2;
        else
            otmp.quan = 1;
        break;

    case AMULET_CLASS:
        if (rn2(10) && (otmp.otyp === ONAMES.AMULET_OF_STRANGULATION
                        || otmp.otyp === ONAMES.AMULET_OF_RESTFUL_SLEEP))
            curse(otmp);
        else
            blessorcurse(otmp, 10);
        break;

    case VENOM_CLASS:
    case CHAIN_CLASS:
    case BALL_CLASS:
        break;

    case POTION_CLASS:
    case SCROLL_CLASS:
        blessorcurse(otmp, 4);
        break;

    case SPBOOK_CLASS:
        otmp.spestudied = 0;
        blessorcurse(otmp, 17);
        break;

    case ARMOR_CLASS:
        if (rn2(10)
            && (otmp.otyp === ONAMES.FUMBLE_BOOTS
                || otmp.otyp === ONAMES.LEVITATION_BOOTS
                || otmp.otyp === ONAMES.HELM_OF_OPPOSITE_ALIGNMENT
                || otmp.otyp === ONAMES.GAUNTLETS_OF_FUMBLING || !rn2(11))) {
            curse(otmp);
            otmp.spe = -rne(3);
        } else if (!rn2(10)) {
            otmp.blessed = rn2(2);
            otmp.spe = rne(3);
        } else {
            blessorcurse(otmp, 10);
        }
        if (artif && !rn2(40 + (10 * nartifact_exist()))) {
            /* mk_artifact() — artifacts not ported */
        }
        break;

    case WAND_CLASS:
        if (otmp.otyp === ONAMES.WAN_WISHING)
            otmp.spe = 1;
        else if (otmp.otyp === ONAMES.WAN_STASIS)
            otmp.spe = rn1(4, 3);
        else
            otmp.spe = rn1(5, (objects[otmp.otyp].oc_dir === NODIR) ? 11 : 4);
        blessorcurse(otmp, 17);
        otmp.recharged = 0;
        break;

    case RING_CLASS:
        if (objects[otmp.otyp].oc_charged) {
            blessorcurse(otmp, 3);
            if (rn2(10)) {
                if (rn2(10) && bcsign(otmp))
                    otmp.spe = bcsign(otmp) * rne(3);
                else
                    otmp.spe = rn2(2) ? rne(3) : -rne(3);
            }
            /* make useless +0 rings much less common */
            if (otmp.spe === 0)
                otmp.spe = rn2(4) - rn2(3);
            /* negative rings are usually cursed */
            if (otmp.spe < 0 && rn2(5))
                curse(otmp);
        } else if (rn2(10) && (otmp.otyp === ONAMES.RIN_TELEPORTATION
                               || otmp.otyp === ONAMES.RIN_POLYMORPH
                               || otmp.otyp === ONAMES.RIN_AGGRAVATE_MONSTER
                               || otmp.otyp === ONAMES.RIN_HUNGER || !rn2(9))) {
            curse(otmp);
        }
        break;

    case ROCK_CLASS:
        if (otmp.otyp === ONAMES.STATUE) {
            /* possibly overridden by mkcorpstat() */
            otmp.corpsenm = rndmonnum();
            /* include/mondata.h:11 verysmall(ptr) is msize < MZ_SMALL */
            if (!(game.mons[otmp.corpsenm].msize < MZ_SMALL)
                && rn2(Math.trunc(level_difficulty() / 2) + 10) > 10) {
                /* add_to_container(otmp, mkobj(SPBOOK_no_NOVEL, FALSE)) —
                   SPBOOK_no_NOVEL takes mkobj's rnd_class() branch, which is
                   not ported; the container add itself makes no draw. */
                mkobj(SPBOOK_CLASS, false);
            }
        }
        /* boulder init'd below in the 'regardless of !init' code */
        break;

    case COIN_CLASS:
        break; /* do nothing */

    default:
        break;
    }
}

// include/objclass.h — oc_dir value used by the wand charge formula.
const NODIR = 1;
// include/monflag.h:178
const MZ_SMALL = 1;

// src/mkobj.c mksobj() — create a specific object type.
//
// Only the identity and o_id allocation are ported so far. mksobj_init(), which
// carries the per-class enchantment, blessing, corpse-type and artifact draws,
// needs artifacts and monster-hatching and lands with those subsystems. Nothing
// here invents a draw it cannot justify.
export function mksobj(otyp, init, artif) {
    const objects = game.objects;
    const otmp = {
        otyp,
        oclass: objects[otyp].oc_class,
        quan: 1,
        spe: 0,
        blessed: 0,
        cursed: 0,
        o_id: next_ident(),
    };
    if (init)
        mksobj_init(otmp, artif);
    return otmp;
}

// src/dungeon.c Is_rogue_level() / Inhell — neither is reachable on the levels
// the public corpus generates, but the branches exist so the class table is
// selected the way C selects it rather than being assumed.
function Is_rogue_level() {
    return game.level?.flags?.is_rogue_level === true;
}
function Inhell() {
    return game.dungeons?.[game.u?.uz?.dnum]?.flags?.hellish === true;
}
