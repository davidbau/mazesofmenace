// src/mkobj.c place_object() — C PREPENDS to fobj:
//
//     otmp->nobj = fobj;
//     fobj = otmp;
//
// so the level's object list is newest-first, and anything that walks it in
// order sees the most recently created object first. dog_goal()'s search walks
// it calling dogfood() on each, and dogfood() draws, so the order is part of
// the PRNG contract.
export function place_object(otmp, x, y) {
    /* src/mkobj.c:2328 — otmp2 is the head of the cell's pile chain; in the
       flat floor list the first entry at (x,y) plays that role. */
    const otmp2 = (game.level.objects || []).find(o => o.ox === x && o.oy === y);

    otmp.ox = x;
    otmp.oy = y;

    /* src/mkobj.c:2331 — a boulder landing on a cell that doesn't already
       show a boulder makes the point opaque. */
    if (otmp.otyp === ONAMES.BOULDER) {
        if (!otmp2 || otmp2.otyp !== ONAMES.BOULDER)
            block_point(x, y); /* vision */
    }

    /* src/mkobj.c place_object() tail — without this, an object that was
       extracted (where == OBJ_FREE) and then re-floored can't be extracted
       again: obj_extract_self's OBJ_FREE arm leaves it in level.objects. */
    otmp.where = OBJ_FLOOR;
    (game.level.objects ||= []).unshift(otmp);
}

// src/mkobj.c:3661 obj_nexto_xy(), find a mergable object on this or an
// adjacent square. The adjacent scan always spends two draws to choose its
// horizontal and vertical order, even when there is no matching object.
export function obj_nexto_xy(obj, x, y, recurs) {
    const here = (game.level.objects || []).find((otmp) =>
        otmp !== obj && otmp.where === OBJ_FLOOR
        && otmp.ox === x && otmp.oy === y
        && otmp.otyp === obj.otyp && mergable(otmp, obj));
    if (here || !recurs)
        return here || null;

    const dx = rn2(2) ? -1 : 1;
    const dy = rn2(2) ? -1 : 1;
    const ex = x - dx, ey = y - dy;
    for (let fx = ex; Math.abs(fx - ex) < 3; fx += dx) {
        for (let fy = ey; Math.abs(fy - ey) < 3; fy += dy) {
            if (isok(fx, fy) && (fx !== x || fy !== y)) {
                const otmp = obj_nexto_xy(obj, fx, fy, false);
                if (otmp)
                    return otmp;
            }
        }
    }
    return null;
}

// src/mkobj.c:3702 obj_absorb(); obj1 and obj2 are {v} boxes like the C's
// pointer-to-pointer arguments
export async function obj_absorb(obj1, obj2) {
    let otmp1, otmp2;
    let o1wt, o2wt;
    let agetmp;

    /* don't let people dumb it up */
    if (obj1 && obj2) {
        otmp1 = obj1.v;
        otmp2 = obj2.v;
        if (otmp1 && otmp2 && otmp1 !== otmp2) {
            await globby_bill_fixup(otmp1, otmp2);
            if (otmp1.bknown !== otmp2.bknown)
                otmp1.bknown = otmp2.bknown = 0;
            if (otmp1.rknown !== otmp2.rknown)
                otmp1.rknown = otmp2.rknown = 0;
            if (otmp1.greased !== otmp2.greased)
                otmp1.greased = otmp2.greased = 0;
            if (otmp1.orotten || otmp2.orotten)
                otmp1.orotten = otmp2.orotten = 1;
            o1wt = otmp1.oeaten ? otmp1.oeaten : otmp1.owt;
            o2wt = otmp2.oeaten ? otmp2.oeaten : otmp2.owt;
            /* averaging the relative ages is less likely to overflow
               than averaging the absolute ages directly */
            agetmp = Math.trunc(((game.moves - otmp1.age) * o1wt
                                 + (game.moves - otmp2.age) * o2wt)
                                / (o1wt + o2wt));
            /* convert relative age back to absolute age */
            otmp1.age = game.moves - agetmp;
            otmp1.owt += o2wt;
            if (otmp1.oeaten || otmp2.oeaten)
                otmp1.oeaten = o1wt + o2wt;
            otmp1.quan = 1;
            if (otmp1.globby && otmp2.globby) {
                /* average (not weighted, no pun intended) the two globs'
                   shrink timers and use that to give otmp1 a new timer */
                let tm1 = stop_timer(SHRINK_GLOB, otmp1),
                    tm2 = stop_timer(SHRINK_GLOB, otmp2);

                tm1 = Math.trunc(((tm1 ? tm1 : 25) + (tm2 ? tm2 : 25) + 1) / 2);
                start_glob_timeout(otmp1, tm1);
            }
            /* get rid of second glob, return augmented first one */
            obj_extract_self(otmp2);
            /* dealloc_obj(otmp2) */
            obj2.v = null;
            return otmp1;
        }
    }

    /* impossible("obj_absorb: not called with two actual objects") */
    return null;
}

