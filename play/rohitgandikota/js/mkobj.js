// src/mkobj.c:536 nextoid() — pick the split-off object's id.
//
// Draws NOTHING, unlike next_ident(). It walks context.ident forward until the
// new id gives the same price adjustment as the parent's, so a stack that
// splits does not change price, and it leaves context.ident on the id it used.
// That last part is why it cannot be replaced by next_ident(): the two advance
// context.ident by different amounts and every later object id would shift.
function nextoid(oldobj, newobj) {
    let trylimit = 256;             /* limit of 4 suffices at present */
    let oid = game.context.ident - 1; /* loop increment will reverse -1 */

    const olddif = oid_price_adjustment(oldobj, oldobj.o_id);
    let newdif;
    do {
        ++oid;
        if (!oid)                   /* avoid using 0 (in case value wrapped) */
            ++oid;
        newdif = oid_price_adjustment(newobj, oid);
    } while (newdif !== olddif && --trylimit >= 0);
    game.context.ident = oid;       /* update 'last ident used' */
    next_ident();                   /* increment context.ident for next use,
                                       mkobj.c:549 -- ONE rnd(2) per split.
                                       (The seed0361 gen-time scare that once
                                       kept this draw out was a CORPSTAT_NONE
                                       crash, not a phantom split; see STATUS
                                       "identification cluster" entries.) */
    return oid;
}


// src/mkobj.c:457 splitobj() — split num items off obj into a new object.
//
// Draws nothing. Ported for dog_eat(), which splits a single item off a food
// stack so a pet eats one ration rather than the whole pile.
//
// Not ported, each recorded rather than faked: splitbill (shops), the timer
// and light-source splits, and the Lua reference bookkeeping. copy_oextra is
// approximated by carrying the fields our object model actually has.
export function splitobj(obj, num) {
    /* can't split containers; C panics here */
    if (obj.cobj || num <= 0 || obj.quan <= num)
        note_unported_obj('splitobj:panic');

    const otmp = { ...obj };        /* *otmp = *obj -- copies whole structure */
    otmp.oextra = null;
    otmp.o_id = nextoid(obj, otmp);
    otmp.timed = 0;                 /* not timed, yet */
    otmp.lamplit = 0;               /* ditto */
    otmp.owornmask = 0;             /* new object isn't worn */
    obj.quan -= num;
    obj.owt = weight(obj);
    otmp.quan = num;
    otmp.owt = weight(otmp);
    otmp.pickup_prev = 0;

    game.context.objsplit = game.context.objsplit || {};
    game.context.objsplit.parent_oid = obj.o_id;
    game.context.objsplit.child_oid = otmp.o_id;

    /* C inserts the child immediately after the parent in both floor chains.
     * The port represents those chains with one level object array. */
    if (obj.where === OBJ_FLOOR) {
        const objects = game.level?.objects;
        const index = objects?.indexOf(obj) ?? -1;
        if (index >= 0)
            objects.splice(index + 1, 0, otmp);
    } else if (obj.where === OBJ_INVENT) {
        const index = (game.invent || []).indexOf(obj);
        if (index >= 0)
            game.invent.splice(index + 1, 0, otmp);
    }

    if (obj.unpaid)
        splitbill(obj, otmp);
    if (obj.timed)
        obj_split_timers(obj, otmp);
    if (obj_sheds_light(obj))
        obj_split_light_source(obj, otmp);

    return otmp;
}

// src/mkobj.c:556 unsplitobj() -- find the other half of the most recent
// split and merge the pair back together.
export async function unsplitobj(obj) {
    let list;
    switch (obj.where) {
    case OBJ_INVENT:
        list = game.invent || [];
        break;
    case OBJ_MINVENT:
        list = obj.ocarry?.minvent || [];
        break;
    case OBJ_CONTAINED:
        list = obj.ocontainer?.cobj || [];
        break;
    default:
        return null;
    }

    const split = game.context?.objsplit || {};
    let parent = null, child = null, target = 0;
    if (obj.o_id === split.child_oid) {
        child = obj;
        target = split.parent_oid;
    } else if (obj.o_id === split.parent_oid) {
        parent = obj;
        target = split.child_oid;
    }
    if (!target)
        return null;
    if (!parent)
        parent = list.find(candidate => candidate.o_id === target) || null;
    if (!child)
        child = list.find(candidate => candidate.o_id === target) || null;
    if (!parent || !child)
        return null;

    return await merged({ o: parent }, { o: child }) ? parent : null;
}

// src/mkobj.c:521 next_ident(); one rnd(2) per new object or monster id.
export function next_ident() {
    const ctx = game.context;
    const id = ctx.ident || 1;
    ctx.ident = id + rnd(2); /* ready for next new object or monster */
    if (!ctx.ident)
        ctx.ident = rnd(2) + 1; /* id 1 is reserved */
    return id;
}

// src/mkobj.c:270 mkobj() — select a type of item from a class.
//
// Two draws: rnd(100) walks the class table, then
// rnd(oclass_prob_totals[oclass]) walks objects[] by oc_prob. Both are visible
// in the recordings as mkobj.c:280 and mkobj.c:289.
export function mkobj(oclass, artif) {
    const objects = game.objects;
    let tprob, i, prob;

    if (oclass === RANDOM_CLASS) {
        const iprobs = Is_rogue_level() ? rogueprobs
                     : Inhell() ? hellprobs
                     : mkobjprobs;
        let idx = 0;
        for (tprob = rnd(100); (tprob -= iprobs[idx][0]) > 0; idx++)
            continue;
        oclass = iprobs[idx][1];
    }

    /* src/mkobj.c:285 — SPBOOK_no_NOVEL draws differently: rnd_class() over the
       spellbooks stopping at SPE_BLANK_PAPER, which excludes SPE_NOVEL. That
       range sums to 999 where the full SPBOOK_CLASS total is 1000. */
    if (oclass === SPBOOK_no_NOVEL) {
        i = rnd_class(game.bases[OCLASSES.SPBOOK_CLASS], ONAMES.SPE_BLANK_PAPER);
        oclass = OCLASSES.SPBOOK_CLASS;     /* for the sanity check below */
    } else {
        prob = rnd(game.oclass_prob_totals[oclass]);
        i = game.bases[oclass];
        while ((prob -= objects[i].oc_prob) > 0)
            ++i;
    }

    /* src/mkobj.c:295 — C's probtype guard. It resets i when the walk lands
       outside the class, which changes WHICH object is returned, so leaving it
       out is not merely dropping a diagnostic. If it ever fires, oc_prob or
       oclass_prob_totals is wrong. */
    if (objects[i].oc_class !== oclass || !obj_descr_name(i)) {
        note_unported_obj(`probtype error oclass=${oclass} i=${i}`);
        i = game.bases[oclass];
    }

    return mksobj(i, true, artif);
}

