// src/objnam.c:5403 rnd_class() — pick within an otyp range by oc_prob.
// Falls back to a flat rn1() when the whole range has zero probability, which
// is a different draw, not just a different value.
export function rnd_class(first, last) {
    const objects = game.objects;
    let sum = 0;

    if (last > first) {
        for (let i = first; i <= last; i++)
            sum += objects[i].oc_prob;
        if (!sum)
            return rn1(last - first + 1, first);
        let x = rnd(sum);
        for (let i = first; i <= last; i++)
            if ((x -= objects[i].oc_prob) <= 0)
                return i;
    }
    return (first === last) ? first : 0 /* STRANGE_OBJECT */;
}

