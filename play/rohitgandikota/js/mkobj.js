// src/mkobj.c:521 next_ident()
// One rnd(2) per created object or monster. Cheap to overlook and it appears
// between every pair of object draws in the recordings.
export function next_ident() {
    const ctx = game.context;
    const id = ctx.ident || 1;
    ctx.ident = id + rnd(2); /* ready for next new object or monster */
    if (!ctx.ident)
        ctx.ident = rnd(2) + 1; /* id 1 is reserved */
    return id;
}

// src/mkobj.c:270 mkobj() — select a type of item from a class.
//
// Two draws: rnd(100) walks the class table, then
// rnd(oclass_prob_totals[oclass]) walks objects[] by oc_prob. Both are visible
// in the recordings as mkobj.c:280 and mkobj.c:289.
export function mkobj(oclass, artif) {
    const objects = game.objects;
    let tprob, i, prob;

    if (oclass === RANDOM_CLASS) {
        const iprobs = Is_rogue_level() ? rogueprobs
                     : Inhell() ? hellprobs
                     : mkobjprobs;
        let idx = 0;
        for (tprob = rnd(100); (tprob -= iprobs[idx][0]) > 0; idx++)
            continue;
        oclass = iprobs[idx][1];
    }

    /* SPBOOK_no_NOVEL takes the rnd_class() path in C; ordinary classes walk
       the per-class probability total. */
    prob = rnd(game.oclass_prob_totals[oclass]);
    i = game.bases[oclass];
    while ((prob -= objects[i].oc_prob) > 0)
        ++i;

    return mksobj(i, true, artif);
}

// include/obj.h:260-268 — weapon-ish predicates. oc_skill is oc_subtyp.
// P_SHURIKEN and P_BOW bound the thrown/fired weapon skills.
const P_BOW = 26, P_SHURIKEN = 31;   /* include/skills.h */
function is_multigen(otmp, objects) {
    const o = objects[otmp.otyp];
    return otmp.oclass === WEAPON_CLASS
        && o.oc_subtyp >= -P_SHURIKEN && o.oc_subtyp <= -P_BOW;
}
function is_poisonable(otmp, objects) {
    return is_multigen(otmp, objects);   /* plus permapoisoned(), not ported */
}

// src/mkobj.c bcsign()
function bcsign(otmp) {
    return (otmp.blessed ? 1 : 0) - (otmp.cursed ? 1 : 0);
}

function curse(otmp) { otmp.cursed = 1; otmp.blessed = 0; }
function bless(otmp) { otmp.blessed = 1; otmp.cursed = 0; }

// src/mkobj.c:1846 blessorcurse()
export function blessorcurse(otmp, chance) {
    if (otmp.blessed || otmp.cursed)
        return;
    if (!rn2(chance)) {
        if (!rn2(2)) curse(otmp); else bless(otmp);
    }
}

