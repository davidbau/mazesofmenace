// src/mkobj.c:315 mkbox_cnts() — fill a container.
//
// The capacity `n` depends on whether the box is locked, and the loop count is
// rn2(n + 1), so an unlocked large box and a locked chest draw different
// numbers of times before anything is created.
export function mkbox_cnts(box) {
    let n;
    box.cobj = [];

    switch (box.otyp) {
    case ONAMES.ICE_BOX:
        n = 20;
        break;
    case ONAMES.CHEST:
        n = box.olocked ? 7 : 5;
        break;
    case ONAMES.LARGE_BOX:
        n = box.olocked ? 5 : 3;
        break;
    case ONAMES.SACK:
    case ONAMES.OILSKIN_SACK:
        /* initial inventory: a sack starts out empty */
        if ((game.moves ?? 1) <= 1 && !game.in_mklev) {
            n = 0;
            break;
        }
        /* FALLTHRU */
    case ONAMES.BAG_OF_HOLDING:
        n = 1;
        break;
    default:
        n = 0;
        break;
    }

    for (n = rn2(n + 1); n > 0; n--) {
        let otmp;
        if (box.otyp === ONAMES.ICE_BOX) {
            otmp = mksobj(ONAMES.CORPSE, true, false);
            otmp.age = 0;
        } else {
            let tprob, idx = 0;
            for (tprob = rnd(100); (tprob -= boxiprobs[idx][0]) > 0; idx++)
                continue;
            otmp = mkobj(boxiprobs[idx][1], false);
            if (!otmp) continue;

            if (otmp.oclass === COIN_CLASS) {
                otmp.quan = rnd(level_difficulty() + 2) * rnd(75);
            } else {
                while (otmp.otyp === ONAMES.ROCK) {
                    otmp.otyp = rnd_class(ONAMES.DILITHIUM_CRYSTAL,
                                          ONAMES.LOADSTONE);
                    if (otmp.quan > 2) otmp.quan = 1;
                }
            }
            if (box.otyp === ONAMES.BAG_OF_HOLDING) {
                if (Is_mbag(otmp)) {
                    otmp.otyp = ONAMES.SACK;
                    otmp.spe = 0;
                } else {
                    while (otmp.otyp === ONAMES.WAN_CANCELLATION)
                        otmp.otyp = rnd_class(ONAMES.WAN_LIGHT,
                                              ONAMES.WAN_LIGHTNING);
                }
            }
        }
        box.cobj.push(otmp);
    }
}

