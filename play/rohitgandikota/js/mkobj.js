// src/mkobj.c:196 mkobj_erosions() — random chance of erosion or grease.
export function mkobj_erosions(otmp) {
    const objects = game.objects;

    if (may_generate_eroded(otmp, objects)) {
        /* a small fraction generate eroded or possibly erodeproof; an item
           that generates eroded is never erodeproof, and vice versa */
        if (!rn2(100)) {
            otmp.oerodeproof = 1;
        } else {
            if (!rn2(80) && (is_flammable(otmp, objects)
                             || is_rustprone(otmp, objects)
                             || is_crackable(otmp, objects))) {
                do {
                    otmp.oeroded = (otmp.oeroded || 0) + 1;
                } while (otmp.oeroded < 3 && !rn2(9));
            }
            if (!rn2(80) && (is_rottable(otmp, objects)
                             || is_corrodeable(otmp, objects))) {
                do {
                    otmp.oeroded2 = (otmp.oeroded2 || 0) + 1;
                } while (otmp.oeroded2 < 3 && !rn2(9));
            }
        }
        /* and very rarely, greased */
        if (!rn2(1000))
            otmp.greased = 1;
    }
}

// src/mkobj.c mksobj() — create a specific object type.
//
// Only the identity and o_id allocation are ported so far. mksobj_init(), which
// carries the per-class enchantment, blessing, corpse-type and artifact draws,
// needs artifacts and monster-hatching and lands with those subsystems. Nothing
// here invents a draw it cannot justify.
export function mksobj(otyp, init, artif) {
    const objects = game.objects;
    const otmp = {
        otyp,
        oclass: objects[otyp].oc_class,
        quan: 1,
        spe: 0,
        blessed: 0,
        cursed: 0,
        oeaten: 0,
        age: Math.max(game.moves ?? 1, 1),
        corpsenm: NON_PM,
        /* C's newobj() zeroes the structure before mksobj() calls weight().
           HEAVY_IRON_BALL treats a nonzero cached weight as an adjusted
           punishment ball, so this field must start at zero, not undefined. */
        owt: 0,
        o_id: next_ident(),
    };
    unknow_object(otmp);

    /* src/mkobj.c:1197 — mkobj_erosions() is the last statement of
       mksobj_init(), not of mksobj(), so an uninitialised object must not
       draw for erosion. */
    if (init)
        mksobj_init(otmp, artif);

    /* src/mkobj.c:1200-1227 — "some things must get done (corpsenm, timers)
       even if init = 0". This block is what makes a corpse draw rndmonnum()
       for its species and rn2(2) for its gender before mkcorpstat() overrides
       the species; the draws happen either way. */
    switch (otmp.otyp) {
    case ONAMES.CORPSE:
        if (otmp.corpsenm === NON_PM) {
            otmp.corpsenm = undead_to_corpse(rndmonnum());
            if (game.mvitals[otmp.corpsenm].mvflags & (G_NOCORPSE | G_GONE))
                otmp.corpsenm = pmIndexOf(game.urole?.mnum);
        }
        /* FALLTHRU */
    case ONAMES.STATUE:
    case ONAMES.FIGURINE:
        if (otmp.corpsenm === NON_PM)
            otmp.corpsenm = rndmonnum();
        if (otmp.corpsenm !== NON_PM) {
            const ptr = game.mons[otmp.corpsenm];
            otmp.spe = is_neuter(ptr) ? CORPSTAT_NEUTER
                     : is_female(ptr) ? CORPSTAT_FEMALE
                     : is_male(ptr) ? CORPSTAT_MALE
                     : rn2(2) ? CORPSTAT_FEMALE : CORPSTAT_MALE;
        }
        /* FALLTHRU */
    case ONAMES.EGG:
        set_corpsenm(otmp, otmp.corpsenm);
        break;
    case ONAMES.BOULDER:
        otmp.next_boulder = 0;
        break;
    case ONAMES.POT_OIL:
        otmp.age = MAX_OIL_IN_FLASK;
        otmp.fromsink = 0;
        break;
    case ONAMES.SPE_NOVEL: {
        /* src/mkobj.c:1246 — every novel gets a Discworld title at
           creation; the rn2 over the title table is in the stream */
        otmp.novelidx = -1; /* "none of the above"; will be changed */
        const box = { idx: otmp.novelidx };
        oname(otmp, noveltitle(box), ONAME_NO_FLAGS);
        otmp.novelidx = box.idx;
        break;
    }
    default:
        break;
    }

    /* src/mkobj.c:1257 — every object gets its weight cached at creation, and
       every later reader uses that field rather than recomputing. Omitting it
       left obj.owt undefined on every object in the game, which made
       inv_weight() return NaN and silently disabled encumbrance; it also meant
       the owt assignments in splitobj(), dog_eat() and mkroom's court chest
       were writing to a field nothing maintained. */
    otmp.owt = weight(otmp);
    return otmp;
}

