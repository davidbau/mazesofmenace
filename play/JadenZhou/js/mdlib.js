// mdlib.js -- the build and version information shown by #version.
// C ref: mdlib.c (FOR_RUNTIME), version.c doextversion(), date.c
// populate_nomakedefs(), nhlua.c get_lua_version()
//
// The compile-time configuration is the recorder build's
// (nethack-c/recorder: unix with the macOS hints, tty only, no sound
// library): build_opts[] keeps the entries whose #ifdef conditions that
// build satisfies, in mdlib.c order.

