/* C ref: mdlib.c window_opts[] (TTY_GRAPHICS only), soundlib_opts[] */
const window_opts = [
    { id: "tty",
      /* assume that one or more of IBMgraphics, DECgraphics
         can be enabled; we can't tell from here whether that is accurate */
      name: "traditional text with optional line-drawing", valid: false },
];
const soundlib_opts = [
    { text_id: "soundlib_nosound", valid: false },
];

/* C ref: mdlib.c STOREOPTTEXT() */
function STOREOPTTEXT(line) {
    opttext.push(line);
}

// C ref: mdlib.c count_and_validate_winopts()
function count_and_validate_winopts() {
    let cnt = 0;
    for (const w of window_opts) {
        ++cnt;
        w.valid = true;
    }
    return cnt;
}

// C ref: mdlib.c count_and_validate_soundlibopts()
function count_and_validate_soundlibopts() {
    let cnt = 0;
    for (const s of soundlib_opts) {
        ++cnt;
        s.valid = true;
    }
    return cnt;
}

// C ref: mdlib.c opt_out_words() -- returns the new length
function opt_out_words(str, length) {
    while (str) {
        const sp = str.indexOf(' ');
        const word = (sp >= 0) ? str.slice(0, sp) : str;
        if (length + word.length > COLNO - 5) {
            STOREOPTTEXT(optbuf);
            optbuf = opt_indent;
            length = opt_indent.length;
        } else {
            optbuf += " ";
            length++;
        }
        optbuf += word;
        length += word.length;
        str = (sp >= 0) ? str.slice(sp + 1) : "";
    }
    return length;
}

// C ref: mdlib.c build_options()
function build_options() {
    let length, cnt = 0;
    const defwinsys = "tty"; /* DEFAULT_WINDOW_SYS */

    build_savebones_compat_string();
    STOREOPTTEXT(optbuf);
    optbuf = `${opt_indent}NetHack version ${VERSION_MAJOR}.${VERSION_MINOR}.${PATCHLEVEL}\n`;
    STOREOPTTEXT(optbuf);
    optbuf = "Options compiled into this edition:";
    STOREOPTTEXT(optbuf);
    optbuf = "";
    length = COLNO + 1; /* force 1st item onto new line */
    length = opt_out_words(`${datamodel(0)} data model,`, length);
    const opts = build_opts();
    for (let i = 0; i < opts.length; i++)
        length = opt_out_words(`${opts[i]}${(i < opts.length - 1) ? "," : "."}`, length);
    STOREOPTTEXT(optbuf);
    optbuf = "";
    const winsyscnt = count_and_validate_winopts();
    STOREOPTTEXT(optbuf);
    optbuf = `Supported windowing system${(winsyscnt > 1) ? "s" : ""}:`;
    STOREOPTTEXT(optbuf);
    optbuf = "";
    length = COLNO + 1; /* force 1st item onto new line */
    for (const w of window_opts) {
        if (!w.valid)
            continue;
        let buf = `"${w.id}"`;
        if (w.name !== w.id)
            buf += ` (${w.name})`;
        /*
         * 1 : foo.
         * 2 : foo and bar,
         * 3+: for, bar, and quux,
         *
         * 2+ will be followed by " with a default of..."
         */
        buf += (winsyscnt === 1) ? "." /* no 'default' */
               : (winsyscnt === 2 && cnt === 0) ? " and"
                 : (cnt === winsyscnt - 2) ? ", and"
                   : ",";
        length = opt_out_words(buf, length);
        cnt++;
    }
    if (cnt > 1) {
        /* loop ended with a comma; opt_out_words() will insert a space */
        length = opt_out_words(`with a default of "${defwinsys}".`, length);
    }
    cnt = 0;
    STOREOPTTEXT(optbuf);
    optbuf = "";
    const soundlibcnt = count_and_validate_soundlibopts();
    STOREOPTTEXT(optbuf);
    optbuf = `Supported soundlib${(soundlibcnt > 1) ? "s" : ""}:`;
    STOREOPTTEXT(optbuf);
    optbuf = "";
    length = COLNO + 1; /* force 1st item onto new line */
    /* USER_SOUNDS isn't defined */
    for (const s of soundlib_opts) {
        if (!s.valid)
            continue;
        let soundlib = s.text_id;
        if (soundlib.startsWith("soundlib_"))
            soundlib = soundlib.slice(9);
        let buf = `"${soundlib}"`;
        /*
         * 1 : foo.
         * 2 : foo and bar.
         * 3+: for, bar, and quux.
         */
        buf += (soundlibcnt === 1 || cnt === soundlibcnt - 1)
               ? "." /* no 'with default' */
               : (soundlibcnt === 2 && cnt === 0) ? " and"
                 : (cnt === soundlibcnt - 2) ? ", and"
                   : ",";
        length = opt_out_words(buf, length);
        cnt++;
    }
    STOREOPTTEXT(optbuf);
    optbuf = "";
    {
        const lua_info = [
            "", "NetHack 5.0.* uses the 'Lua' interpreter to process some data:", "",
            "    :LUACOPYRIGHT:", "",
            "    \"Permission is hereby granted, free of charge, to any person obtaining",
            "     a copy of this software and associated documentation files (the ",
            "     \"Software\"), to deal in the Software without restriction including",
            "     without limitation the rights to use, copy, modify, merge, publish,",
            "     distribute, sublicense, and/or sell copies of the Software, and to ",
            "     permit persons to whom the Software is furnished to do so, subject to",
            "     the following conditions:",
            "     The above copyright notice and this permission notice shall be",
            "     included in all copies or substantial portions of the Software.\"",
        ];
        /* add lua copyright notice;
           ":TAG:" substitutions are deferred to caller */
        for (const line of lua_info)
            STOREOPTTEXT(line);
    }
    /* end with a blank line */
    STOREOPTTEXT("");
}

// C ref: mdlib.c runtime_info_init()
function runtime_info_init() {
    if (!done_runtime_opt_init_once) {
        done_runtime_opt_init_once = 1;
        build_savebones_compat_string();
        /* construct the current version number: make_version();
           populate_nomakedefs(&version) (date.c) */
        game.nomakedefs_version_id = version_id_string(PINNED_BUILD_DATE);
        opttext = [];
        build_options();
    }
}

// C ref: mdlib.c do_runtime_info() -- rtcontext is { n }
function do_runtime_info(rtcontext) {
    let retval = null;

    if (!done_runtime_opt_init_once)
        runtime_info_init();
    if (opttext.length && rtcontext)
        if (rtcontext.n >= 0 && rtcontext.n < opttext.length) {
            retval = opttext[rtcontext.n];
            rtcontext.n += 1;
        }
    return retval;
}

// C ref: version.c getversionstring() -- no git sha, branch or prefix
// (and no RUNTIME_PORT_ID), so nothing is added in parentheses
function getversionstring() {
    if (!game.nomakedefs_version_id)
        runtime_info_init();
    return game.nomakedefs_version_id;
}

// C ref: nhlua.c get_lua_version()
function get_lua_version() {
    const sbi = { flags: NHL_SB_VERSION, memlimit: 1 * 1024 * 1024, steps: 0,
                  perpcall: 1 * 1024 * 1024 };

    if (!game.lua_ver) {
        const L = nhl_init(sbi);

        if (L) {
            /* LUA_VERSION yields "<major>.<minor>" although we check to see
               whether it is "Lua-<major>.<minor>" and strip prefix if so;
               LUA_RELEASE is <LUA_VERSION>.<LUA_VERSION_RELEASE> but doesn't
               get set up as a lua global */
            let vs = (typeof L.globals._RELEASE === 'string')
                     ? L.globals._RELEASE : LUA_RELEASE;
            if (vs.slice(0, 3).toLowerCase() === "lua") {
                vs = vs.slice(3);
                if (vs[0] === '-' || vs[0] === ' ')
                    vs = vs.slice(1);
            }
            game.lua_ver = vs;
        }
        nhl_done(L);
        game.lua_copyright = LUA_COPYRIGHT;
    }
    return game.lua_ver;
}

// C ref: version.c insert_rtoption()
function insert_rtoption(buf) {
    if (!game.lua_ver)
        get_lua_version();

    const rt_opts = [
        [":PATMATCH:", regex_id],
        [":LUAVERSION:", game.lua_ver || ""],
        [":LUACOPYRIGHT:", game.lua_copyright || ""],
    ];
    for (const [token, value] of rt_opts) {
        if (buf.toLowerCase().includes(token.toLowerCase()) && value)
            buf = buf.replace(token, value); /* strsubst() */
        /* we don't break out of the loop after a match; there might be
           other matches on the same line */
    }
    return buf;
}

// C ref: hacklib.c tabexpand() -- expand tabs into spaces (8-column stops)
function tabexpand(sbuf) {
    let buf = '', idx = 0;
    for (const c of sbuf) {
        if (c === '\t') {
            do
                buf += ' ';
            while (++idx % 8);
        } else {
            buf += c;
            ++idx;
        }
    }
    return buf.slice(0, 255);
}

// C ref: version.c doextversion() -- the #version command
export async function doextversion() {
    const rtcontext = { n: 0 };
    let rtbuf;
    let buf;
    const win = tty_create_nhwindow(NHW_TEXT);
    /* OPTIONS_AT_RUNTIME (version.c defines it): use_dlb is FALSE */
    let done_rt = false;
    let prolog;

    /* instead of using ``display_file(OPTIONS_USED,TRUE)'' we handle
       the file manually so we can include dynamic version info */

    buf = getversionstring();
    /* if extra text (git info) is present, put it on separate line
       but don't wrap on (x86) */
    let p = -1;
    if (buf.length >= COLNO)
        p = buf.lastIndexOf('(');
    if (p > 0 && buf[p - 1] === ' ' && buf[p + 1] !== 'x') {
        await tty_putstr(win, 0, buf.slice(0, p - 1));
        await tty_putstr(win, 0, ` ${buf.slice(p)}`);
    } else {
        await tty_putstr(win, 0, buf);
    }

    prolog = true; /* to skip indented program name */
    for (;;) {
        if (!done_rt) {
            if ((rtbuf = do_runtime_info(rtcontext)) === null) {
                done_rt = true;
                continue;
            }
            buf = rtbuf.slice(0, 255);
        } else {
            break;
        }
        /* strip_newline() */
        const nl = buf.lastIndexOf('\n');
        if (nl >= 0)
            buf = buf.slice(0, (nl > 0 && buf[nl - 1] === '\r') ? nl - 1 : nl);
        if (buf.includes('\t'))
            buf = tabexpand(buf);

        if (buf && buf[0] !== ' ') {
            /* found outdented header; insert a separator since we'll
               have skipped corresponding blank line inside the file */
            await tty_putstr(win, 0, "");
            prolog = false;
        }
        /* skip blank lines and prolog (progame name plus version) */
        if (prolog || !buf)
            continue;

        if (buf.includes(':'))
            buf = insert_rtoption(buf);

        if (buf)
            await tty_putstr(win, 0, buf);
    }
    await tty_display_nhwindow(win, false);
    await tty_destroy_nhwindow(win);
    return ECMD_OK;
}
