/* C ref: patchlevel.h */
const VERSION_MAJOR = 5, VERSION_MINOR = 0, PATCHLEVEL = 0;
/* NH_DEVEL_STATUS is NH_STATUS_RELEASED: no status text, no EDITLEVEL */

/* C ref: global.h PORT_ID for the macOS build */
const PORT_ID = "MacOS";

/* C ref: date.c populate_nomakedefs() -- the recorder pins the build date
   string ("Mon DD YYYY HH:MM:SS", the __DATE__ " " __TIME__ shape) */
const PINNED_BUILD_DATE = "May  2 2026 12:00:00";

/* C ref: sys/share/posixregex.c regex_id[] */
const regex_id = "posixregex";

/* C ref: lib/lua-5.4.8/src/lua.h LUA_RELEASE, LUA_COPYRIGHT */
const LUA_VERSION_MAJOR = "5", LUA_VERSION_MINOR = "4", LUA_VERSION_RELEASE = "8";
const LUA_VERSION = `Lua ${LUA_VERSION_MAJOR}.${LUA_VERSION_MINOR}`;
const LUA_RELEASE = `${LUA_VERSION}.${LUA_VERSION_RELEASE}`;
const LUA_COPYRIGHT = `${LUA_RELEASE}  Copyright (C) 1994-2025 Lua.org, PUC-Rio`;

// C ref: hacklib.c dm[], datamodel() -- dm[0] holds the build's sizes of
// short, int, long, long long and pointer (a 64-bit unix build)
const MAX_D = 5;
const dm = [
    { sz: [2, 4, 8, 8, 8], datamodel: "", dmplatform: "" },
    { sz: [2, 4, 4, 8, 4], datamodel: "ILP32LL64", dmplatform: "x86 32-bit" }, /* Windows or Unix */
    { sz: [2, 4, 4, 8, 8], datamodel: "IL32LLP64", dmplatform: "Windows x64 64-bit" },
    { sz: [2, 4, 8, 8, 8], datamodel: "I32LP64", dmplatform: "Unix 64-bit" },
    { sz: [2, 8, 8, 8, 8], datamodel: "ILP64", dmplatform: "Unix ILP64" }, /* HAL, SPARC64 */
];
export function datamodel(retidx) {
    const unknown = "Unknown";

    for (let i = 1; i < dm.length; ++i) {
        let matchcount = 0;
        for (let j = 0; j < MAX_D; ++j) {
            if (dm[0].sz[j] === dm[i].sz[j])
                ++matchcount;
        }
        if (matchcount === MAX_D)
            return (retidx === 0) ? dm[i].datamodel : dm[i].dmplatform;
    }
    return unknown;
}

// C ref: mdlib.c mdlib_version_string()
function mdlib_version_string(delim) {
    return `${VERSION_MAJOR}${delim}${VERSION_MINOR}${delim}${PATCHLEVEL}`;
}

// C ref: mdlib.c version_id_string() -- date_via_env is FALSE at run time
function version_id_string(build_date) {
    const statusbuf = "", subbuf = ""; /* no PORT_SUB_ID */
    return `${PORT_ID} NetHack${subbuf} Version ${mdlib_version_string(".")}${statusbuf}`
        + ` - last build ${build_date}.`;
}

/* C ref: mdlib.c static state of the opttext[] collection */
let opttext = [];
let optbuf = "";
let done_runtime_opt_init_once = 0;
let save_bones_compat_buf = "";
const opt_indent = "    ";

// C ref: mdlib.c build_savebones_compat_string() -- VERSION_COMPATIBILITY
