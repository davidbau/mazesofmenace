// rumors.js — random text lines from the rumors/engrave/epitaph files.
// C ref: rumors.c getrumor(), init_rumors(), get_rnd_line(), get_rnd_text(),
// unpadline().
//
// C reads files that util/makedefs.c builds from dat/rumors.tru,
// dat/rumors.fal, dat/engrave.txt and dat/epitaph.txt. js/ may not read
// files, so this module builds the same file contents in memory from the
// source text in js/rumors_data.js, as makedefs does (padline(), headers,
// grep0() conditionals). xcrypt() is omitted: it preserves line lengths and
// get_rnd_line() decrypts again, so offsets and results are unchanged.

import { game } from './gstate.js';
import { rn2, rn2_fnptr } from './rng.js';
import { RUMORS_TRU, RUMORS_FAL, ENGRAVE_TXT, EPITAPH_TXT } from './rumors_data.js';

const BUFSZ = 256;
export const MD_PAD_RUMORS = 60; /* global.h */
export const RUMORFILE = 'rumors';
export const ENGRAVEFILE = 'engrave';
export const EPITAPHFILE = 'epitaph';

// C ref: makedefs.c Dont_Edit_Data
const Dont_Edit_Data =
    '#\tThis data file is generated by \'makedefs\'.  Do not edit. \n';

// C ref: makedefs.c padline()
function padline(line, padlength) {
    /* line includes its newline */
    let len = line.length;
    if (len <= padlength) {
        let body = line.slice(0, -1);
        while (len++ < padlength)
            body += '_';
        line = body + '\n';
    }
    return line;
}

// C ref: makedefs.c grep0() -- '^?SYM' / '^!SYM' / '^:' / '^.' blocks.
// makedefs' symbol table for a unix build defines MAIL (unixconf.h).
const grep_defined = new Set(['MAIL']);
function grep0(lines) {
    const out = [];
    const stack = [];
    let printing = true;
    for (const l of lines) {
        if (l[0] === '^') {
            const op = l[1];
            if (op === '?' || op === '!') {
                stack.push(printing);
                const def = grep_defined.has(l.slice(2).trim());
                printing = printing && (op === '?' ? def : !def);
            } else if (op === ':') {
                const outer = stack.length ? stack[stack.length - 1] : true;
                printing = outer && !printing;
            } else if (op === '.') {
                printing = stack.length ? stack.pop() : true;
            }
            continue;
        }
        if (printing) out.push(l);
    }
    return out;
}

function hex6(n) { return n.toString(16).padStart(6, '0'); }
function dec(n, w) { return String(n).padStart(w, '0'); }

// C ref: makedefs.c do_rumors() / read_rumors_file()
function build_rumors_file() {
    const tru = RUMORS_TRU.map(l => padline(l + '\n', MD_PAD_RUMORS)).join('');
    const fal = RUMORS_FAL.map(l => padline(l + '\n', MD_PAD_RUMORS)).join('');
    /* the header has fixed-width fields, so its length is known up front */
    const hdrlen = Dont_Edit_Data.length
        + '0000,000000,000000;0000,000000,000000;0,0,000000\n'.length;
    const true_start = hdrlen;
    const false_start = true_start + tru.length;
    const eof_offset = false_start + fal.length;
    const header = Dont_Edit_Data
        + `${dec(RUMORS_TRU.length, 4)},${dec(tru.length, 6)},${hex6(true_start)};`
        + `${dec(RUMORS_FAL.length, 4)},${dec(fal.length, 6)},${hex6(false_start)};`
        + `0,0,${hex6(eof_offset)}\n`;
    return header + tru + fal;
}

// C ref: makedefs.c do_rnd_access_file()
function build_rnd_access_file(lines, deflt_content) {
    let s = Dont_Edit_Data;
    s += padline(deflt_content + '\n', MD_PAD_RUMORS);
    for (const l of grep0(lines)) {
        if (l[0] !== '#' && l !== '')
            s += padline(l + '\n', MD_PAD_RUMORS);
    }
    return s;
}

let datafiles = null;
function dlb_files() {
    if (!datafiles) {
        datafiles = {
            [RUMORFILE]: build_rumors_file(),
            [ENGRAVEFILE]: build_rnd_access_file(ENGRAVE_TXT,
                /* default engraving */
                'No matter where you go, there you are.'),
            [EPITAPHFILE]: build_rnd_access_file(EPITAPH_TXT,
                /* default epitaph:  parody of the default engraving */
                'No matter where I went, here I am.'),
        };
    }
    return datafiles;
}

// dlb.c-like in-memory file handle
function dlb_fopen(name) {
    const data = dlb_files()[name];
    return data == null ? null : { data, pos: 0 };
}
function dlb_fseek(fh, off, whence) {
    fh.pos = whence === 'SEEK_END' ? fh.data.length + off
             : whence === 'SEEK_CUR' ? fh.pos + off : off;
}
function dlb_ftell(fh) { return fh.pos; }
/* fgets(): up to bufsiz-1 chars, stopping after a newline; null at EOF */
function dlb_fgets(bufsiz, fh) {
    if (fh.pos >= fh.data.length) return null;
    let end = fh.data.indexOf('\n', fh.pos);
    end = end < 0 ? fh.data.length : end + 1;
    end = Math.min(end, fh.pos + bufsiz - 1);
    const s = fh.data.slice(fh.pos, end);
    fh.pos = end;
    return s;
}

// C ref: rumors.c unpadline()
function unpadline(line) {
    let p = line.length;
    /* remove newline if still present; caller should have stripped it */
    if (p > 0 && line[p - 1] === '\n')
        --p;
    /* remove padding */
    while (p > 0 && line[p - 1] === '_')
        --p;
    return line.slice(0, p);
}

// C ref: rumors.c get_rnd_line()
function get_rnd_line(fh, bufsiz, rng, startpos, endpos, padlength) {
    let buf = '';
    let filechunksize, chunkoffset;
    let trylimit;

    if (!endpos) {
        dlb_fseek(fh, 0, 'SEEK_END');
        endpos = dlb_ftell(fh);
    }
    filechunksize = endpos - startpos;

    if (filechunksize < 1)
        return buf;

    /*
     * Position randomly which will probably be in the middle of a line.
     * Read the rest of that line, then use the next one.  If there's no
     * next line (ie, end of file), go back to beginning and use first.
     *
     * When short lines have been padded to length N, only accept long
     * lines if we land within last N+1 characters (+1 is for newline
     * which hasn't been stripped away yet), effectively shortening
     * them to normal length.  That yields even selection distribution.
     */
    for (trylimit = 10; trylimit > 0; --trylimit) {
        chunkoffset = rng(filechunksize);
        dlb_fseek(fh, startpos + chunkoffset, 'SEEK_SET');
        buf = dlb_fgets(bufsiz, fh) ?? '';
        if (!padlength || buf.length <= padlength + 1)
            break;
    }
    /* use next line; reaching endpos is equivalent to end-of-file */
    let next = null;
    if (dlb_ftell(fh) >= endpos || (next = dlb_fgets(bufsiz, fh)) === null) {
        /* assume failure is due to end-of-file; go back to start */
        dlb_fseek(fh, startpos, 'SEEK_SET');
        next = dlb_fgets(bufsiz, fh) ?? '';
    }
    buf = next;
    const newl = buf.indexOf('\n');
    if (newl >= 0)
        buf = buf.slice(0, newl);
    /* xcrypt(): not applied when the files are built (see header) */
    /* strip padding that makedefs adds to short lines */
    if (padlength)
        buf = unpadline(buf);
    return buf;
}

// C ref: rumors.c init_rumors()
function init_rumors(fp) {
    const g = game;
    dlb_fgets(BUFSZ, fp); /* skip "don't edit" comment */
    const line = dlb_fgets(BUFSZ, fp) || '';
    const m = /^(\d+),(\d+),([0-9a-f]+);(\d+),(\d+),([0-9a-f]+);0,0,([0-9a-f]+)\n/.exec(line);
    if (m && +m[2] > 0 && +m[5] > 0) {
        g.true_rumor_size = +m[2];
        g.true_rumor_start = parseInt(m[3], 16);
        g.false_rumor_size = +m[5];
        g.false_rumor_start = parseInt(m[6], 16);
        g.true_rumor_end = g.true_rumor_start + g.true_rumor_size;
        g.false_rumor_end = g.false_rumor_start + g.false_rumor_size;
    } else {
        g.true_rumor_size = -1; /* init failed */
    }
}

// C ref: rumors.c getrumor()
/* exclude_cookie is a hack used because we sometimes want to get rumors in a
 * context where messages such as "You swallowed the fortune!" that refer to
 * cookies should not appear.  This has no effect for true rumors since none
 * of them contain such references anyway.
 */
export function getrumor(truth, rumor_buf, exclude_cookie) {
    const g = game;
    let rumors;
    let beginning, ending;
    const cookie_marker = '[cookie] ';
    const marklen = cookie_marker.length;
    let adjtruth;

    rumor_buf.s = '';
    if ((g.true_rumor_size ?? 0) < 0) /* a previous try failed */
        return rumor_buf.s;

    rumors = dlb_fopen(RUMORFILE);
    if (rumors) {
        let count = 0;

        do {
            rumor_buf.s = '';
            if (!g.true_rumor_size) { /* if this is 1st outrumor() */
                init_rumors(rumors);
                if (g.true_rumor_size < 0) { /* init failed */
                    rumor_buf.s = `Error reading "${RUMORFILE}".`;
                    return rumor_buf.s;
                }
            }
            /*
             *  input:      1    0   -1
             *   rn2 \ +1  2=T  1=T  0=F
             *   adj./ +0  1=T  0=F -1=F
             */
            switch (adjtruth = truth + rn2(2)) {
            case 2: /*(might let a bogus input arg sneak thru)*/
            case 1:
                beginning = g.true_rumor_start;
                ending = g.true_rumor_end;
                break;
            case 0: /* once here, 0 => false rather than "either"*/
            case -1:
                beginning = g.false_rumor_start;
                ending = g.false_rumor_end;
                break;
            default:
                rumor_buf.s = 'Oops...';
                return rumor_buf.s;
            }
            rumor_buf.s = get_rnd_line(rumors, BUFSZ, rn2_fnptr,
                                       beginning, ending, MD_PAD_RUMORS);
        } while (count++ < 50 && exclude_cookie
                 && rumor_buf.s.startsWith(cookie_marker));
        if (count >= 50) {
            /* impossible("Can't find non-cookie rumor?") */
        } else if (!g.in_mklev) {
            /* exercise(A_WIS, (adjtruth > 0)): attrib exercise is not
               reached during level creation */
        }
    }
    if (!exclude_cookie && rumor_buf.s.startsWith(cookie_marker)) {
        /* remove cookie_marker from the string */
        rumor_buf.s = rumor_buf.s.slice(marklen);
    }
    return rumor_buf.s;
}

// C ref: rumors.c get_rnd_text()
/* Gets a random line of text from file 'fname', and returns it.
   rng is the random number generator to use, and should act like rn2 does. */
export function get_rnd_text(fname, buf, rng, padlength) {
    const fh = dlb_fopen(fname);

    buf.s = '';
    if (fh) {
        let starttxt = 0;

        /* skip "don't edit" comment */
        dlb_fgets(BUFSZ, fh);
        /* obtain current file position */
        dlb_fseek(fh, 0, 'SEEK_CUR');
        starttxt = dlb_ftell(fh);

        /* get a randomly chosen line; it comes back decrypted and unpadded */
        buf.s = get_rnd_line(fh, BUFSZ, rng, starttxt, 0, padlength);
    }
    return buf.s;
}

// test hook: lengths of the built files (compare with C's dat/ outputs)
export function _datafile_lengths() {
    const f = dlb_files();
    return Object.fromEntries(Object.entries(f).map(([k, v]) => [k, v.length]));
}
