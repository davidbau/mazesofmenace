export function exportascii_sfo_char(nhfp, d_char, myname, cnt)
{
    let i;
    let j;
    let uintval;
    const sval = C.stackAlloc((1 * 128));
    let usrc = d_char;
    let udest = C.strbuf;
    /* cnt is the number of characters */
    for ((i = C.cast("Int32", 0)); Number(i < cnt); (++i))
        {
            if (Number(!!(Number(!!((Number(C.cast("Int32", C.load("Uint8", usrc)) < 32))) || !!((Number(C.cast("Int32", C.load("Uint8", usrc)) == 92))))) || !!((Number(C.cast("Int32", C.load("Uint8", usrc)) == 124)))))
                {
                    C.store("Uint8", (udest++), C.cast("Uint8", C.cast("Uint8", 92)));
                    (uintval = C.cast("Uint32", C.cast("Uint32", C.load("Uint8", (usrc++)))));
                    C.sprintf(sval, C.literal("%03u"), C.va(["Uint32", uintval]));
                    for ((j = C.cast("Int32", 0)); Number(j < 3); (++j))
                        C.store("Uint8", (udest++), C.cast("Uint8", C.cast("Uint8", C.load("Int8", (sval + Number(j) * 1)))));
                }
            else
                {
                    C.store("Uint8", (udest++), C.cast("Uint8", C.load("Uint8", (usrc++))));
                }
        }
    C.store("Uint8", udest, C.cast("Uint8", C.cast("Uint8", 0)));
    C.callLocal(put_savefield , nhfp, C.strbuf, C.strlen(C.strbuf));
}

