export function exportascii_sfi_char(nhfp, d_char, myname, cnt)
{
    let i;
    let j;
    let sval;
    const n = C.stackAlloc((1 * 4));
    let rstr;
    let src;
    let dest;
    /* cnt is the length of the string */
    (rstr = C.callLocal(get_savefield , nhfp, C.strbuf, BigInt((1 * 2560))));
    if (Number(!(rstr)))
        {
            (C.record(nhfp, "NHFILE").eof = C.cast("Int8", (C.cast("Int8", 1))));
            return;
        }
    (src = rstr);
    (dest = d_char);
    for ((i = C.cast("Int32", 0)); Number(i < cnt); (++i))
        {
            if (Number(C.cast("Int32", C.load("Int8", src)) == 92))
                {
                    (src++);
                    for ((j = C.cast("Int32", 0)); Number(j < 4); (++j))
                        {
                            if (Number(j < 3))
                                C.store("Int8", (n + Number(j) * 1), C.cast("Int8", C.load("Int8", (src++))));
                            else
                                C.store("Int8", (n + Number(j) * 1), C.cast("Int8", C.cast("Int8", 0)));
                        }
                    (sval = C.cast("Int32", C.atoi(n)));
                    C.store("Int8", (dest++), C.cast("Int8", C.cast("Int8", sval)));
                }
            else
                C.store("Int8", (dest++), C.cast("Int8", C.load("Int8", (src++))));
        }
}

export function get_savefield(nhfp, inbuf, inbufsz)
{
    let ep;
    let sep;
    let res = 0;
    if (Number(((res = C.fgets(inbuf, C.cast("Int32", inbufsz), C.record(nhfp, "NHFILE").fpdef))) != 0))
        {
            (C.record(nhfp, "NHFILE").rcount++);
            (ep = C.strchr(inbuf, 10));
            if (Number(!(ep)))
                {
                    /* newline missing */
                    if (Number(C.strlen(inbuf) < (C.cast("BigUint64", (inbufsz - C.cast("BigUint64", 2))))))
                        {
                            /* likely the last line of file is just
                   missing a newline; process it anyway  */
                            (ep = C.eos(inbuf));
                        }
                }
            if (ep)
                C.store("Int8", ep, C.cast("Int8", C.cast("Int8", 0)));
            /* remove newline */
            (sep = C.strchr(inbuf, 124));
            if (sep)
                (sep++);
            return sep;
        }
    C.store("Int8", (inbuf + Number(0) * 1), C.cast("Int8", C.cast("Int8", 0)));
    (C.record(nhfp, "NHFILE").eof = C.cast("Int8", (C.cast("Int8", 1))));
    return inbuf;
}

